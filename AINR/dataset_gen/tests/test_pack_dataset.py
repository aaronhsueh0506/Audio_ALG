"""Regression tests for pack_dataset.py's input contract and
effective_rms_dbfs recording.

The input contract is now just "a directory of NNNNNN.wav": no meta.json, no
per-sample sidecar, no contract version. What still has to hold, and is pinned
here, is everything that can be checked from the audio itself --

  * a `tmp.NNNNNN.wav` left behind by a crashed write is never packed (the
    original release-blocking bug: a naive recursive glob('*.wav') matched it
    and silently shipped a crash artifact as a training sample);
  * a hole in the numbering is refused unless --allow-index-gaps says the
    subset is deliberate;
  * every file must be 2-channel, the same length, finite, and (without
    --target-sr) the same native rate -- one bad file stops the pack rather
    than being silently dropped;
  * effective_rms_dbfs describes the audio as actually stored, after any
    resample and after the cast to the packed dtype;
  * the output is written atomically.

-- and that leftover JSON from a corpus generated by the older, sidecar-writing
generator is simply ignored, so that data does not have to be regenerated.
"""

import json
import math
import os
import tempfile
import types
import unittest
from pathlib import Path
from unittest.mock import patch

import torch
import torchaudio

from dataset_gen.dataset import rms_dbfs
from dataset_gen.gen_dataset import _sample_wav_path, _save_pair_atomic, _tmp_path
from dataset_gen.loader import load_packed_dataset
from dataset_gen.pack_dataset import DatasetContractError, pack


def _make_batch(tmp, indices_and_audio):
    """Build a `tmp/pairs/` directory of NNNNNN.wav files.

    `indices_and_audio` is a list of (index, noisy, clean, sr) tuples.
    Returns the pairs_dir path.
    """
    pairs_dir = os.path.join(tmp, 'pairs')
    os.makedirs(pairs_dir, exist_ok=True)
    for index, noisy, clean, sr in indices_and_audio:
        _save_pair_atomic(pairs_dir, index, noisy, clean, sr)
    return pairs_dir


def _tone(sr, freq=200, amp=0.5, seconds=1.0):
    t = torch.linspace(0, seconds, int(sr * seconds), dtype=torch.float32)
    return amp * torch.sin(2 * math.pi * freq * t)


def _pack_args(input_dir, output_path, target_sr=None, quality='best',
               dtype='float32', allow_index_gaps=False, shard_clips=None,
               overwrite=False):
    return types.SimpleNamespace(
        input=input_dir, output=output_path, dtype=dtype,
        target_sr=target_sr, quality=quality,
        allow_index_gaps=allow_index_gaps,
        shard_clips=shard_clips, overwrite=overwrite,
    )


class EffectiveRmsDbfsTest(unittest.TestCase):
    def test_present_and_correctly_shaped(self):
        with tempfile.TemporaryDirectory() as tmp:
            sr = 16000
            noisy, clean = _tone(sr, 200, 0.5), _tone(sr, 200, 0.3)
            in_dir = _make_batch(tmp, [(0, noisy, clean, sr), (1, noisy, clean, sr)])

            out_path = os.path.join(tmp, 'packed.pt')
            pack(_pack_args(in_dir, out_path))

            payload = torch.load(out_path, weights_only=True)
            self.assertIn('effective_rms_dbfs', payload)
            self.assertEqual(tuple(payload['effective_rms_dbfs'].shape), (2, 2))

    def test_matches_manual_rms_when_no_resample(self):
        with tempfile.TemporaryDirectory() as tmp:
            sr = 16000
            noisy, clean = _tone(sr, 200, 0.5), _tone(sr, 200, 0.3)
            in_dir = _make_batch(tmp, [(0, noisy, clean, sr)])

            out_path = os.path.join(tmp, 'packed.pt')
            pack(_pack_args(in_dir, out_path))

            payload = torch.load(out_path, weights_only=True)
            # Read back through the same torchaudio.load() path pack() itself
            # uses -- 16-bit WAV round-trip quantization means this is not
            # bit-exact against the original float tensor.
            reloaded, _ = torchaudio.load(_sample_wav_path(in_dir, 0))
            expected_noisy = rms_dbfs(reloaded[0])
            expected_clean = rms_dbfs(reloaded[1])
            self.assertAlmostEqual(
                payload['effective_rms_dbfs'][0, 0].item(), expected_noisy, places=2)
            self.assertAlmostEqual(
                payload['effective_rms_dbfs'][0, 1].item(), expected_clean, places=2)

    def test_reflects_post_resample_level_not_pre_resample(self):
        # A narrowband high-frequency tone: most of its energy sits above
        # 8 kHz (the new Nyquist after a 48k->16k downsample), so the
        # post-resample RMS is measurably lower than the pre-resample RMS --
        # exactly the drift this field exists to catch (see README.md).
        with tempfile.TemporaryDirectory() as tmp:
            source_sr = 48000
            high_tone = _tone(source_sr, 18000, 0.5)
            in_dir = _make_batch(tmp, [(0, high_tone, high_tone, source_sr)])

            pre_resample_rms = rms_dbfs(high_tone)

            out_path = os.path.join(tmp, 'packed.pt')
            pack(_pack_args(in_dir, out_path, target_sr=16000))

            payload = torch.load(out_path, weights_only=True)
            self.assertEqual(payload['sr'], 16000)
            post_resample_rms = payload['effective_rms_dbfs'][0, 0].item()
            # The 18 kHz tone is almost entirely removed by the anti-alias
            # filter ahead of the 16 kHz Nyquist (8 kHz) -- a large, easily
            # asserted drop, not a rounding-noise-level difference.
            self.assertLess(
                post_resample_rms, pre_resample_rms - 20.0,
                "effective_rms_dbfs must reflect the ACTUAL post-resample "
                "level, not the pre-resample value carried forward"
            )

    def test_omitted_target_sr_still_records_effective_rms(self):
        # No --target-sr at all (pack-as-is): still recorded, since nothing
        # else in the packed payload carries per-sample level information.
        with tempfile.TemporaryDirectory() as tmp:
            sr = 48000
            noisy = clean = _tone(sr, 300, 0.4)
            in_dir = _make_batch(tmp, [(0, noisy, clean, sr)])

            out_path = os.path.join(tmp, 'packed.pt')
            pack(_pack_args(in_dir, out_path, target_sr=None))

            payload = torch.load(out_path, weights_only=True)
            self.assertIn('effective_rms_dbfs', payload)
            self.assertTrue(torch.isfinite(payload['effective_rms_dbfs']).all())

    def test_measured_on_packed_dtype_not_pre_cast_float32(self):
        # float16 has ~3 decimal digits of precision; measuring on the
        # pre-cast float32 tensor instead of data[i] (what's ACTUALLY
        # stored) would describe a signal the packed payload doesn't
        # contain. Recompute RMS directly from the packed float16 data and
        # compare against effective_rms_dbfs -- if the field were measured
        # pre-cast, this comparison would (rarely) disagree past float16's
        # ~3-decimal-digit precision.
        with tempfile.TemporaryDirectory() as tmp:
            sr = 16000
            noisy = clean = _tone(sr, 200, 0.5)
            in_dir = _make_batch(tmp, [(0, noisy, clean, sr)])
            out_path = os.path.join(tmp, 'packed.pt')

            pack(_pack_args(in_dir, out_path, dtype='float16'))
            payload = torch.load(out_path, weights_only=True)
            expected = rms_dbfs(payload['data'][0, 0].float())
            self.assertAlmostEqual(
                payload['effective_rms_dbfs'][0, 0].item(), expected, places=4)


class SampleScanTest(unittest.TestCase):
    """What counts as a sample is the filename and nothing else."""

    def test_temp_file_from_a_crashed_write_is_never_packed(self):
        with tempfile.TemporaryDirectory() as tmp:
            sr = 16000
            noisy, clean = _tone(sr, 200), _tone(sr, 300)
            in_dir = _make_batch(tmp, [(0, noisy, clean, sr)])
            # Reproduce a crash mid-write: a tmp.NNNNNN.wav left behind by
            # _save_pair_atomic's temp-file step, never renamed into place.
            # With no sidecar to mark completion, the temp NAME is now the
            # only thing keeping this file out of the corpus.
            torchaudio.save(_tmp_path(_sample_wav_path(in_dir, 1)),
                            torch.stack([noisy, clean]), sr, bits_per_sample=16)

            out_path = os.path.join(tmp, 'packed.pt')
            pack(_pack_args(in_dir, out_path))

            payload = torch.load(out_path, weights_only=True)
            self.assertEqual(payload['n_samples'], 1)
            self.assertEqual(payload['sample_indices'], [0])

    def test_non_numeric_wav_name_is_ignored(self):
        with tempfile.TemporaryDirectory() as tmp:
            sr = 16000
            noisy, clean = _tone(sr, 200), _tone(sr, 300)
            in_dir = _make_batch(tmp, [(0, noisy, clean, sr)])
            torchaudio.save(os.path.join(in_dir, 'listen_to_this.wav'),
                            torch.stack([noisy, clean]), sr, bits_per_sample=16)

            out_path = os.path.join(tmp, 'packed.pt')
            pack(_pack_args(in_dir, out_path))
            self.assertEqual(
                torch.load(out_path, weights_only=True)['sample_indices'], [0])

    def test_leftover_sidecars_from_an_older_corpus_are_ignored(self):
        """Data generated before the sidecars were dropped must still pack.

        The whole point of the JSON-free contract: an existing corpus is not
        regenerated, its stale metadata is simply not read.
        """
        with tempfile.TemporaryDirectory() as tmp:
            sr = 16000
            noisy, clean = _tone(sr, 200), _tone(sr, 300)
            in_dir = _make_batch(tmp, [(0, noisy, clean, sr), (1, noisy, clean, sr)])
            Path(in_dir, '000000.json').write_text(
                json.dumps({'index': 0, 'snr_db': 3.0}))
            Path(in_dir, '000001.json').write_text('{ this one is even corrupt')
            Path(tmp, 'meta.json').write_text(
                json.dumps({'contract_version': 4, 'batch_n_samples': 999}))

            out_path = os.path.join(tmp, 'packed.pt')
            pack(_pack_args(in_dir, out_path))
            payload = torch.load(out_path, weights_only=True)
            self.assertEqual(payload['sample_indices'], [0, 1])

    def test_index_gap_is_rejected_by_default(self):
        with tempfile.TemporaryDirectory() as tmp:
            sr = 16000
            noisy, clean = _tone(sr, 200), _tone(sr, 300)
            in_dir = _make_batch(tmp, [
                (0, noisy, clean, sr), (1, noisy, clean, sr),
                (3, noisy, clean, sr),   # index 2 missing
            ])
            out_path = os.path.join(tmp, 'packed.pt')
            with self.assertRaises(DatasetContractError):
                pack(_pack_args(in_dir, out_path))

    def test_index_gap_accepted_with_allow_index_gaps(self):
        with tempfile.TemporaryDirectory() as tmp:
            sr = 16000
            noisy, clean = _tone(sr, 200), _tone(sr, 300)
            in_dir = _make_batch(tmp, [
                (0, noisy, clean, sr), (1, noisy, clean, sr),
                (3, noisy, clean, sr),
            ])
            out_path = os.path.join(tmp, 'packed.pt')
            pack(_pack_args(in_dir, out_path, allow_index_gaps=True))
            payload = torch.load(out_path, weights_only=True)
            self.assertEqual(payload['sample_indices'], [0, 1, 3])
            self.assertEqual(payload['n_samples'], 3)

    def test_a_batch_not_starting_at_zero_is_fine(self):
        """A shard numbered from --start-idx is contiguous, just not from 0."""
        with tempfile.TemporaryDirectory() as tmp:
            sr = 16000
            noisy, clean = _tone(sr, 200), _tone(sr, 300)
            in_dir = _make_batch(tmp, [(500, noisy, clean, sr),
                                       (501, noisy, clean, sr)])
            out_path = os.path.join(tmp, 'packed.pt')
            pack(_pack_args(in_dir, out_path))
            self.assertEqual(
                torch.load(out_path, weights_only=True)['sample_indices'],
                [500, 501])

    def test_no_wavs_raises(self):
        with tempfile.TemporaryDirectory() as tmp:
            in_dir = _make_batch(tmp, [])
            out_path = os.path.join(tmp, 'packed.pt')
            with self.assertRaises(FileNotFoundError):
                pack(_pack_args(in_dir, out_path))


class PerFileValidationTest(unittest.TestCase):
    """One bad file stops the pack. It is never silently excluded: dropping it
    would both shrink the corpus without saying so and reopen an index gap the
    scan just checked."""

    def test_three_channel_wav_is_rejected(self):
        with tempfile.TemporaryDirectory() as tmp:
            sr = 16000
            noisy, clean = _tone(sr, 200), _tone(sr, 300)
            in_dir = _make_batch(tmp, [(0, noisy, clean, sr)])
            three_channel = torch.stack([noisy, clean, _tone(sr, 400)], dim=0)
            torchaudio.save(_sample_wav_path(in_dir, 0), three_channel, sr,
                            bits_per_sample=16)
            out_path = os.path.join(tmp, 'packed.pt')
            with self.assertRaises(DatasetContractError):
                pack(_pack_args(in_dir, out_path))

    def test_length_mismatch_is_rejected(self):
        with tempfile.TemporaryDirectory() as tmp:
            sr = 16000
            in_dir = _make_batch(tmp, [
                (0, _tone(sr, 200), _tone(sr, 300), sr),
                (1, _tone(sr, 200, seconds=0.5), _tone(sr, 300, seconds=0.5), sr),
            ])
            out_path = os.path.join(tmp, 'packed.pt')
            with self.assertRaises(DatasetContractError):
                pack(_pack_args(in_dir, out_path))

    def test_non_finite_samples_are_rejected(self):
        with tempfile.TemporaryDirectory() as tmp:
            sr = 16000
            noisy, clean = _tone(sr, 200), _tone(sr, 300)
            in_dir = _make_batch(tmp, [(0, noisy, clean, sr)])
            # A float32 WAV can carry NaN; a 16-bit one cannot, so this has to
            # be written as float to exercise the check at all.
            broken = torch.stack([noisy, clean])
            broken[0, 0] = float('nan')
            torchaudio.save(_sample_wav_path(in_dir, 0), broken, sr,
                            encoding='PCM_F', bits_per_sample=32)
            out_path = os.path.join(tmp, 'packed.pt')
            with self.assertRaises(DatasetContractError):
                pack(_pack_args(in_dir, out_path))

    def test_mismatched_native_rate_without_target_sr_is_rejected(self):
        with tempfile.TemporaryDirectory() as tmp:
            in_dir = _make_batch(tmp, [
                (0, _tone(16000, 200), _tone(16000, 300), 16000),
                (1, _tone(48000, 200), _tone(48000, 300), 48000),
            ])
            out_path = os.path.join(tmp, 'packed.pt')
            with self.assertRaises(DatasetContractError):
                pack(_pack_args(in_dir, out_path))

    def test_mismatched_native_rate_is_reconciled_by_target_sr(self):
        """--target-sr resamples every file to one output rate, so mixed
        native rates are legitimate then (e.g. a directory assembled by
        hand from two sources)."""
        with tempfile.TemporaryDirectory() as tmp:
            in_dir = _make_batch(tmp, [
                (0, _tone(16000, 200), _tone(16000, 300), 16000),
                (1, _tone(48000, 200), _tone(48000, 300), 48000),
            ])
            out_path = os.path.join(tmp, 'packed.pt')
            pack(_pack_args(in_dir, out_path, target_sr=16000))
            payload = torch.load(out_path, weights_only=True)
            self.assertEqual(payload['sample_indices'], [0, 1])
            self.assertEqual(payload['sr'], 16000)
            self.assertEqual(payload['source_srs'], [16000, 48000])
            self.assertNotIn('source_sr', payload)


class SampleIndicesPayloadTest(unittest.TestCase):
    def test_sample_indices_trace_packed_rows_to_source_files(self):
        with tempfile.TemporaryDirectory() as tmp:
            sr = 16000
            samples = [(i, _tone(sr, 200 + i), _tone(sr, 300 + i), sr) for i in range(4)]
            in_dir = _make_batch(tmp, samples)
            out_path = os.path.join(tmp, 'packed.pt')
            pack(_pack_args(in_dir, out_path))
            payload = torch.load(out_path, weights_only=True)
            self.assertEqual(payload['sample_indices'], [0, 1, 2, 3])
            self.assertEqual(len(payload['sample_indices']), payload['n_samples'])

    def test_payload_carries_no_contract_fields(self):
        """Nothing in the payload claims a provenance the packer cannot see."""
        with tempfile.TemporaryDirectory() as tmp:
            sr = 16000
            in_dir = _make_batch(tmp, [(0, _tone(sr), _tone(sr, 300), sr)])
            out_path = os.path.join(tmp, 'packed.pt')
            pack(_pack_args(in_dir, out_path))
            payload = torch.load(out_path, weights_only=True)
            self.assertNotIn('contract_version', payload)
            self.assertNotIn('config_hash', payload)


class AtomicPackedWriteTest(unittest.TestCase):
    def test_success_leaves_no_tmp_file(self):
        with tempfile.TemporaryDirectory() as tmp:
            sr = 16000
            noisy, clean = _tone(sr, 200), _tone(sr, 300)
            in_dir = _make_batch(tmp, [(0, noisy, clean, sr)])
            out_path = os.path.join(tmp, 'packed.pt')
            pack(_pack_args(in_dir, out_path))
            self.assertTrue(Path(out_path).exists())
            self.assertFalse(Path(out_path + '.tmp').exists())

    def test_failure_leaves_no_final_file(self):
        with tempfile.TemporaryDirectory() as tmp:
            sr = 16000
            noisy, clean = _tone(sr, 200), _tone(sr, 300)
            in_dir = _make_batch(tmp, [(0, noisy, clean, sr)])
            out_path = os.path.join(tmp, 'packed.pt')
            with patch('dataset_gen.pack_dataset.torch.save',
                       side_effect=RuntimeError('disk full')):
                with self.assertRaises(RuntimeError):
                    pack(_pack_args(in_dir, out_path))
            self.assertFalse(Path(out_path).exists())
            self.assertFalse(Path(out_path + '.tmp').exists())


class ShardedPackTest(unittest.TestCase):
    def test_shard_clips_writes_ordered_shards_and_loader_reads_directory(self):
        with tempfile.TemporaryDirectory() as tmp:
            sr = 16000
            samples = [
                (i, _tone(sr, 200 + i), _tone(sr, 300 + i), sr)
                for i in range(5)
            ]
            in_dir = _make_batch(tmp, samples)
            out_dir = os.path.join(tmp, 'packed')

            pack(_pack_args(in_dir, out_dir, dtype='float16', shard_clips=2))

            paths = sorted(Path(out_dir).glob('shard_*.pt'))
            self.assertEqual(
                [path.name for path in paths],
                ['shard_00000.pt', 'shard_00001.pt', 'shard_00002.pt'])
            payloads = [torch.load(path, weights_only=True) for path in paths]
            self.assertEqual([p['n_samples'] for p in payloads], [2, 2, 1])
            self.assertEqual(
                [i for p in payloads for i in p['sample_indices']],
                [0, 1, 2, 3, 4])
            self.assertEqual(
                [tuple(p['data'].shape[:2]) for p in payloads],
                [(2, 2), (2, 2), (1, 2)])
            self.assertTrue(all(p['data'].dtype == torch.float16
                                for p in payloads))
            self.assertTrue(all(
                tuple(p['effective_rms_dbfs'].shape) == (p['n_samples'], 2)
                for p in payloads))

            dataset = load_packed_dataset(out_dir, expected_sr=sr, mmap=True)
            self.assertEqual(len(dataset), 5)

    def test_non_positive_shard_size_is_rejected(self):
        with tempfile.TemporaryDirectory() as tmp:
            sr = 16000
            in_dir = _make_batch(
                tmp, [(0, _tone(sr, 200), _tone(sr, 300), sr)])
            with self.assertRaisesRegex(ValueError, 'must be positive'):
                pack(_pack_args(
                    in_dir, os.path.join(tmp, 'packed'), shard_clips=0))

    def test_existing_shards_require_overwrite(self):
        with tempfile.TemporaryDirectory() as tmp:
            sr = 16000
            samples = [
                (i, _tone(sr, 200 + i), _tone(sr, 300 + i), sr)
                for i in range(3)
            ]
            in_dir = _make_batch(tmp, samples)
            out_dir = os.path.join(tmp, 'packed')
            pack(_pack_args(in_dir, out_dir, shard_clips=1))

            with self.assertRaisesRegex(FileExistsError, 'already contains'):
                pack(_pack_args(in_dir, out_dir, shard_clips=2))

    def test_failed_overwrite_keeps_old_set_and_removes_staged_temps(self):
        with tempfile.TemporaryDirectory() as tmp:
            sr = 16000
            samples = [
                (i, _tone(sr, 200 + i), _tone(sr, 300 + i), sr)
                for i in range(3)
            ]
            in_dir = _make_batch(tmp, samples)
            out_dir = os.path.join(tmp, 'packed')
            pack(_pack_args(in_dir, out_dir, shard_clips=1))
            old_paths = sorted(Path(out_dir).glob('shard_*.pt'))
            old_bytes = {path.name: path.read_bytes() for path in old_paths}

            # The first two clips stage a complete new shard. The third clip
            # then fails validation, so none of the new set may be published.
            victim = _sample_wav_path(in_dir, 2)
            audio, _ = torchaudio.load(victim)
            audio[0, 0] = float('nan')
            torchaudio.save(victim, audio, sr, encoding='PCM_F', bits_per_sample=32)
            with self.assertRaises(DatasetContractError):
                pack(_pack_args(
                    in_dir, out_dir, shard_clips=2, overwrite=True))

            self.assertEqual(
                {path.name: path.read_bytes() for path in old_paths}, old_bytes)
            self.assertFalse(list(Path(out_dir).glob('shard_*.pt.tmp')))

    def test_successful_overwrite_removes_obsolete_tail_shards(self):
        with tempfile.TemporaryDirectory() as tmp:
            sr = 16000
            samples = [
                (i, _tone(sr, 200 + i), _tone(sr, 300 + i), sr)
                for i in range(3)
            ]
            in_dir = _make_batch(tmp, samples)
            out_dir = os.path.join(tmp, 'packed')
            pack(_pack_args(in_dir, out_dir, shard_clips=1))
            self.assertEqual(len(list(Path(out_dir).glob('shard_*.pt'))), 3)

            pack(_pack_args(
                in_dir, out_dir, shard_clips=2, overwrite=True))
            paths = sorted(Path(out_dir).glob('shard_*.pt'))
            self.assertEqual(
                [path.name for path in paths],
                ['shard_00000.pt', 'shard_00001.pt'])
            self.assertEqual(load_packed_dataset(out_dir).__len__(), 3)

    def test_partial_torch_save_is_removed(self):
        with tempfile.TemporaryDirectory() as tmp:
            sr = 16000
            in_dir = _make_batch(
                tmp, [(0, _tone(sr, 200), _tone(sr, 300), sr)])
            out_dir = os.path.join(tmp, 'packed')

            def fail_after_creating_temp(_payload, path):
                Path(path).write_bytes(b'partial')
                raise RuntimeError('disk full')

            with patch('dataset_gen.pack_dataset.torch.save',
                       side_effect=fail_after_creating_temp):
                with self.assertRaisesRegex(RuntimeError, 'disk full'):
                    pack(_pack_args(in_dir, out_dir, shard_clips=1))

            self.assertFalse(list(Path(out_dir).glob('shard_*.pt')))
            self.assertFalse(list(Path(out_dir).glob('shard_*.pt.tmp')))


